///
/// Spec-independent: the file bodies are the fixed runtime contract (see the
/// Phase 3 Kiota-lite BUILD SPEC §2). Regenerable — this generator is the single
/// source of truth for the fleet's shared transport, so client emits and the
/// runtime emit never drift.
///
/// Invoked via `--emit-target=runtime`; needs no OpenAPI spec.
class RuntimePackageGenerator {
  RuntimePackageGenerator({
    required this.outputDir,
    required this.packageName,
  });

  final String outputDir;
  final String packageName;

  Future<void> generate() async {
    final root = p.join(outputDir, packageName);
    for (final f in _files()) {
      final path = p.join(root, f.path);
      await Directory(p.dirname(path)).create(recursive: true);
      await File(path).writeAsString(f.content);
    }
    try {
      final result = await Process.run(
        'dart',
        ['format', '.'],
        workingDirectory: root,
      );
      if (result.exitCode != 0) {
        print('Warning: dart format exited with code ${result.exitCode}');
      }
    } catch (e) {
      print('Warning: Could not format runtime package: $e');
    }
    print('Generated ${_files().length} runtime files in $root');
  }

  List<GeneratedFile> _files() => [
        GeneratedFile(path: 'pubspec.yaml', content: _pubspec),
        GeneratedFile(path: 'lib/$packageName.dart', content: _barrel),
