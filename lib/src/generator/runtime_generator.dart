/// The HTTP statuses that are worth retrying. Shared between [RetryInterceptor]
/// (which replays them) and the adapter's `validateStatus` (which lets ONLY
/// these reach `onError` so the retry path sees them) — see the build spec D-R2.
const Set<int> kRetryableStatuses = {408, 429, 500, 502, 503, 504};

class RetryInterceptor extends Interceptor {
  RetryInterceptor({
    this.maxRetries = 3,
    this.retryDelay = const Duration(seconds: 1),
    this.retryableStatuses = kRetryableStatuses,
  });

  final int maxRetries;
  final Duration retryDelay;
  final Set<int> retryableStatuses;

  /// Injected by `DioRequestAdapter` so retries reuse the SAME configured dio
  /// (keeps auth/baseUrl/interceptors). Falls back to a bare `Dio()` only if the
  /// interceptor is used stand-alone.
  Dio? _dio;
  set dio(Dio d) => _dio = d;

  @override
  void onError(DioException err, ErrorInterceptorHandler handler) async {
    final requestOptions = err.requestOptions;
    final retryCount = requestOptions.extra['retry_count'] as int? ?? 0;
    final status = err.response?.statusCode;
    if (retryCount < maxRetries &&
        status != null &&
        retryableStatuses.contains(status)) {
      await Future<void>.delayed(retryDelay * (retryCount + 1));
      requestOptions.extra['retry_count'] = retryCount + 1;
      try {
        // FIX: reuse the SAME configured Dio (keeps auth/baseUrl/interceptors).
        // The old core did `Dio().fetch(...)` on a bare client, dropping all of
        // that — a retried 401-refresh or 503 went out unauthenticated / to a
        // relative URL.
        final response = await (_dio ?? Dio()).fetch<dynamic>(requestOptions);
        handler.resolve(response);
      } catch (_) {
        handler.next(err);
      }
    } else {
      handler.next(err);
    }
  }
}

