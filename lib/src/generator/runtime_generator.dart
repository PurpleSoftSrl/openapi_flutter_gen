/// The ONLY dio-touching class. Owns one [Dio], applies the injected
/// [AuthenticationProvider] per request, wires the error/retry/logging
/// interceptors, and maps non-2xx to a typed [ApiException].
class DioRequestAdapter implements RequestAdapter {
  DioRequestAdapter({
    required this.baseUrl,
    AuthenticationProvider? authenticationProvider,
    Dio? dio,
    ApiErrorInterceptor? errorHandler,
    RetryInterceptor? retryInterceptor,
    LoggingInterceptor? loggingInterceptor,
    List<Interceptor> interceptors = const [],
  })  : _auth = authenticationProvider ?? const AnonymousAuthenticationProvider(),
        _dio = dio ?? Dio(),
        _retryableStatuses =
            (retryInterceptor ?? RetryInterceptor()).retryableStatuses {
    _dio.options.baseUrl = baseUrl;
    // Order: error callbacks first (see response), then retry, then log.
    if (errorHandler != null) _dio.interceptors.add(errorHandler);
    final retry = retryInterceptor ?? RetryInterceptor();
    retry.dio = _dio; // fix: retries reuse THIS configured dio
    _dio.interceptors.add(retry);
    if (loggingInterceptor != null) _dio.interceptors.add(loggingInterceptor);
    _dio.interceptors.addAll(interceptors);
  }

  @override
  final String baseUrl;
  final AuthenticationProvider _auth;
  final Dio _dio;
  final Set<int> _retryableStatuses;

  @override
  Future<T> send<T>(
      RequestInformation request, ModelDeserializer<T> deserialize) async {
    final response = await _execute(request, ResponseType.json);
    final data = response.data;
    if (data is Map<String, dynamic>) return deserialize(data);
    if (data is Map) return deserialize(Map<String, dynamic>.from(data));
    throw _mismatch(request, response, 'JSON object', data);
  }

  @override
  Future<List<T>> sendList<T>(
      RequestInformation request, ModelDeserializer<T> deserialize) async {
    final response = await _execute(request, ResponseType.json);
    final data = response.data;
    if (data is List) {
      return data
          .map((e) => deserialize(Map<String, dynamic>.from(e as Map)))
          .toList();
    }
    throw _mismatch(request, response, 'JSON array', data);
  }

  @override
  Future<T> sendPrimitive<T>(RequestInformation request,
      {PrimitiveDeserializer<T>? convert}) async {
    final wantsBytes = T == Uint8List;
    final response =
        await _execute(request, wantsBytes ? ResponseType.bytes : ResponseType.json);
    final data = response.data;
    if (convert != null) return convert(data);
    if (wantsBytes && data is List<int>) return Uint8List.fromList(data) as T;
    return data as T;
  }

  @override
  Future<void> sendNoContent(RequestInformation request) async {
    await _execute(request, ResponseType.json);
  }

