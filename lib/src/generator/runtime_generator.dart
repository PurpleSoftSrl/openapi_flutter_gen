///
/// Generated `*Api` methods build one of these and hand it to a [RequestAdapter].
/// It carries NO dio types and NO model types — the body is already-serialized
/// JSON (`Map`/`List`/primitive from `model.toJson()`), and path/query params are
/// raw values the adapter renders/encodes.
