/// Adds `Authorization: Bearer <token>` — ONLY when the token is present.
///
/// THE BUG FIX: the old `BearerSecurity`/`AuthInterceptor` set the header
/// whenever `token != null`, so an empty string `''` produced a bare
/// `Authorization: Bearer ` which the backend parsed as a malformed token
/// (IDX12709, first-login-impossible). Here null AND empty/whitespace are
/// treated as "no credentials" and NO header is emitted.
class BearerAuthenticationProvider implements AuthenticationProvider {
  const BearerAuthenticationProvider(
    this.tokenProvider, {
    this.headerName = 'Authorization',
    this.scheme = 'Bearer',
  });

  final AccessTokenProvider tokenProvider;
  final String headerName;
  final String scheme;

  @override
  Future<void> authenticateRequest(RequestInformation request) async {
    final token = await tokenProvider.getAuthorizationToken();
    if (token == null || token.trim().isEmpty) return; // <-- no bare "Bearer "
    request.addHeader(headerName, '$scheme $token');
  }
}

